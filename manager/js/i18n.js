  let lang = storage.get(LANG_KEY) === 'ar' ? 'ar' : 'en';
  const listeners = [];
  const globals = {};

  // Apply language, direction and a saved theme straight away.
  const root = document.documentElement;
  root.lang = lang;
  root.dir = LANGS[lang].dir;
  const savedTheme = storage.get('dms.theme');
  if (savedTheme === 'light' || savedTheme === 'dark') root.setAttribute('data-theme', savedTheme);

  function localeTag() { return LANGS[lang].locale + '-u-nu-' + NUMBERING; }

  /** Translate a key. {placeholders} come from params, then from globals. */
  function t(key, params) { return tIn(lang, key, params); }
  /** The same in a fixed language, for text that is written in both (the welcome e-mail). */
  function tIn(language, key, params) {
    let value = translations[language][key];
    if (value === undefined) value = translations.en[key];
    if (value === undefined) return key;
    return value.replace(/\{(\w+)\}/g, function (match, name) {
      if (params && params[name] !== undefined) return String(params[name]);
      if (globals[name] !== undefined) return String(globals[name]);
      return match;
    });
  }

  /** Fills elements that carry data-i18n* attributes. */
  function apply(scope) {
    const rootEl = scope || document;
    rootEl.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    rootEl.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    rootEl.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label'))); });
    rootEl.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    rootEl.querySelectorAll('[data-i18n-alt]').forEach(function (el) { el.setAttribute('alt', t(el.getAttribute('data-i18n-alt'))); });
  }

  function setLang(next) {
    if (!LANGS[next] || next === lang) return;
    lang = next;
    storage.set(LANG_KEY, next);
    root.lang = next;
    root.dir = LANGS[next].dir;
    apply(document);
    listeners.forEach(function (fn) { fn(next); });
  }

  /* ---- Values in the current language ----------------------------------------- */
  function loc(value) { return value && typeof value === 'object' ? value[lang] || value.en || '' : value; }
  function name(person) {
    if (!person) return '';
    const latin = person.name || person.full_name || '';
    return lang === 'ar' ? person.name_ar || latin : latin || person.name_ar || '';
  }
  function field(record, base) {
    return record[base + '_' + lang] || record[base + '_en'] || record[base + '_ar'] || '';
  }
  /** Keeps codes like "CMP-0207" or "A-101" left-to-right inside Arabic sentences. */
  function isolate(text) { return '⁦' + text + '⁩'; }

  /* ---- Formatting -------------------------------------------------------------- */
  function toDate(value) {
    if (value instanceof Date) return value;
    const s = String(value);
    if (/^\d{4}-\d{2}-\d{2}$/.test(s)) {
      const p = s.split('-').map(Number);
      return new Date(p[0], p[1] - 1, p[2]);
    }
    if (/^\d{4}-\d{2}$/.test(s)) {
      const p = s.split('-').map(Number);
      return new Date(p[0], p[1] - 1, 1);
    }
    return new Date(s);
  }
  const DATE_STYLES = {
    full: { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' },
    medium: { day: 'numeric', month: 'short', year: 'numeric' },
    short: { day: 'numeric', month: 'short' },
    weekday: { weekday: 'long' },
    month: { month: 'long', year: 'numeric' },
  };
  function date(value, style) {
    return new Intl.DateTimeFormat(localeTag(), DATE_STYLES[style || 'medium']).format(toDate(value));
  }
  function dateTime(value) {
    return new Intl.DateTimeFormat(localeTag(), { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }).format(toDate(value));
  }
  /** "10:00" -> localised clock time. */
  function time(hhmm) {
    const p = String(hhmm).split(':').map(Number);
    const d = new Date();
    d.setHours(p[0] || 0, p[1] || 0, 0, 0);
    return new Intl.DateTimeFormat(localeTag(), { hour: '2-digit', minute: '2-digit' }).format(d);
  }
  function number(n, options) { return new Intl.NumberFormat(localeTag(), options).format(n); }
  function percent(fraction) { return new Intl.NumberFormat(localeTag(), { style: 'percent', maximumFractionDigits: 0 }).format(fraction); }
  /** "5 minutes ago", "yesterday"; older than a week shows the date. */
  function relative(value) {
    const diff = (toDate(value).getTime() - Date.now()) / 60000;
    const rtf = new Intl.RelativeTimeFormat(localeTag(), { numeric: 'auto' });
    const abs = Math.abs(diff);
    if (abs < 1) return rtf.format(0, 'minute');
    if (abs < 60) return rtf.format(Math.round(diff), 'minute');
    if (abs < 1440) return rtf.format(Math.round(diff / 60), 'hour');
    if (abs < 10080) return rtf.format(Math.round(diff / 1440), 'day');
    return date(value, 'medium');
  }

