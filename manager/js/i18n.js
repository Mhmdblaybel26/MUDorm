/* ==========================================================================
   i18n.js — every visible string (English + Arabic), locale formatting, and
   the storage wrapper used by the other scripts.

   This file is loaded WITHOUT defer, before the page body, so the saved
   language (and theme) are applied to <html lang dir data-theme> before the
   first paint: no flash of the wrong direction.

   Rules:
   - HTML never contains visible text. Elements carry data-i18n="key"
     (also data-i18n-placeholder / -aria-label / -title / -alt) and apply()
     fills them. Scripts call t('key', { param }).
   - Text typed by people (announcements, dishes, rules, requests, notes) is
     typed once, in either language. Readers of the other language get an
     automatic translation (translate.js), shown with dir="auto".
   - Admin-managed content uses *_en / *_ar fields, read with
     field(record, 'title'); the field left empty is filled by translation.
   - The pages keep their texts here; the Laravel API returns stable codes
     (roomFull, mealClosed ...) that the pages translate (api.* keys).
   ========================================================================== */
