  const storage = (function () {
    function area(which) {
      try { return which === 'session' ? global.sessionStorage : global.localStorage; } catch (e) { return null; }
    }
    let available = false;
    try {
      global.localStorage.setItem('dms.check', '1');
      global.localStorage.removeItem('dms.check');
      available = true;
    } catch (e) { available = false; }
    return {
      available: available,
      get: function (key, which) {
        try { const s = area(which); return s ? s.getItem(key) : null; } catch (e) { return null; }
      },
      set: function (key, value, which) {
        try { const s = area(which); if (!s) return false; s.setItem(key, value); return true; } catch (e) { return false; }
      },
      remove: function (key, which) {
        try { const s = area(which); if (s) s.removeItem(key); } catch (e) { /* storage blocked */ }
      },
    };
  })();
